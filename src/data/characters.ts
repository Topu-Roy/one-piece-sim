import type { Character, ConquerorState, DevilFruit, Race, HakiTier, Tier, Weapon } from "../lib/types";

/*
  Hand-authored character pool.

  Per CORE_IDEA.md every stat is individually assigned from canon context — no
  derived formulas, no clean round numbers. The `tier` a character carries into
  a round is a rarity label only; the values below are the source of truth.

  Two pools:
  - NORMAL_POOL: general roster. Any entry can be elevated to Epic at draw time.
  - LEGEND_POOL: curated strongest figures. Only ever appear via the Legend tier
    roll; never in the baseline Normal draw.
*/

// --- compact constructors (reduce boilerplate + keep every field typed) ---

const noConqueror = (): ConquerorState => ({ has: false });

const conqueror = (control: "Uncontrolled" | "Directional" | "Full"): ConquerorState => ({
  has: true,
  control,
});

const noFruit = (): DevilFruit => ({
  type: "None",
  awakened: false,
  offense: 0,
  defense: 0,
  versatility: 0,
});

const fruit = (
  type: Exclude<DevilFruit["type"], "None">,
  awakened: boolean,
  offense: number,
  defense: number,
  versatility: number,
): DevilFruit => ({ type, awakened, offense, defense, versatility });

const weapon = (type: Exclude<Weapon["type"], "None">, proficiency: number): Weapon => ({ type, proficiency });

const noWeapon = (): Weapon => ({ type: "None", proficiency: 0 });

function makeCharacter(
  id: string,
  name: string,
  race: Race,
  armament: HakiTier,
  observation: HakiTier,
  conquerorState: ConquerorState,
  devilFruit: DevilFruit,
  charWeapon: Weapon,
  strength: number,
  speed: number,
  durability: number,
  intelligence: number,
): Character {
  return {
    id,
    name,
    race,
    armament,
    observation,
    conqueror: conquerorState,
    devilFruit,
    weapon: charWeapon,
    strength,
    speed,
    durability,
    intelligence,
  };
}

